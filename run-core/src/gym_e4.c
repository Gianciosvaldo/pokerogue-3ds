static int seed_item(pr_rng *rng, int n)
{
    return n == 1 ? 0 : pr_rng_integer_in_range(rng, 0, n - 1);
}

static const pr_trainer_species *trainer_species(int type)
{
    int lo = 0, hi = pr_trainer_species_count - 1;
    while (lo <= hi) {
        int mid = (lo + hi) / 2;
        if (pr_trainer_species_data[mid].type == type) return &pr_trainer_species_data[mid];
        if (pr_trainer_species_data[mid].type < type) lo = mid + 1; else hi = mid - 1;
    }
    return NULL;
}

static const pr_fixed_member_closure *explicit_closure(int type, int slot)
{
    int lo = 0, hi = (int)(sizeof fixed_member_closures / sizeof fixed_member_closures[0]) - 1;
    while (lo <= hi) {
        int mid = (lo + hi) / 2;
        const pr_fixed_member_closure *c = &fixed_member_closures[mid];
        int cmp = type != c->type ? type - c->type : slot - c->slot;
        if (!cmp) return c;
        if (cmp < 0) hi = mid - 1; else lo = mid + 1;
    }
    return NULL;
}

int pr_run_gen_gym_e4_closure_member(pr_run *run, const pr_trainer_party_ctx *ctx,
                                     int index, int func_key, pr_enemy_gen *out, int *out_species)
{
    const int type = ctx->enemy.trainer_type;
    const pr_trainer_species *ts = trainer_species(type);
    if (!ts) return 0;

    int species = -1;
    bool ignore_evolution = false;

    if (func_key < 0 && ((type >= TRAINER_TYPE_BROCK && type <= TRAINER_TYPE_GRUSHA)
                        || (type >= TRAINER_TYPE_LORELEI && type <= TRAINER_TYPE_DRAYTON))) {
        const int group_index = -func_key - 1;
        if (group_index < 0 || group_index >= ts->n_groups) return 0;
        const pr_signature_group *g = &pr_trainer_signature_groups[ts->group_start + group_index];
        if (!g->n) { run->unported |= PR_RUN_UNDEFINED_UPSTREAM; return -1; }
        species = pr_trainer_signature_species[g->start + seed_item(&run->rng, g->n)];
    } else if (func_key >= 0 && type >= TRAINER_TYPE_LORELEI && type <= TRAINER_TYPE_KIERAN) {
        const pr_fixed_member_closure *cl = explicit_closure(type, func_key);
        if (!cl || !cl->n) return 0;
        species = fixed_member_species[cl->start + seed_item(&run->rng, cl->n)];
        ignore_evolution = cl->ignore_evolution != 0;
    } else {
        return 0;
    }

    const pr_party_template *tpl = ctx->template_;
    const int level = ctx->levels[index];
    const int evo_kind = (tpl->member[index] >> 2) & 3;
    if (!ignore_evolution) {
        species = pr_run_determine_enemy_species(&run->rng, species, level, true, evo_kind, true,
                                                 ctx->classic_wave20_trainer);
        if (species < 0) return -1;
    }

    pr_enemy_gen_ctx ec = ctx->enemy;
    ec.species = species;
    ec.level = level;
    ec.trainer_slot = 1;
    ec.boss = false;
    ec.shiny_lock = false;
    if (pr_run_enemy_pokemon_base(run, &ec, out) < 0) return -1;
    *out_species = species;
    return 1;
}

