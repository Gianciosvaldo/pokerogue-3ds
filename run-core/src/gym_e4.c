int pr_run_fixed_e4_trainer(const pr_run *run, int wave)
{
    int row;
    switch (wave) {
    case CLASSIC_FIXED_BOSS_WAVES_ELITE_FOUR_1: row = 0; break;
    case CLASSIC_FIXED_BOSS_WAVES_ELITE_FOUR_2: row = 1; break;
    case CLASSIC_FIXED_BOSS_WAVES_ELITE_FOUR_3: row = 2; break;
    case CLASSIC_FIXED_BOSS_WAVES_ELITE_FOUR_4: row = 3; break;
    case CLASSIC_FIXED_BOSS_WAVES_CHAMPION: row = 4; break;
    default: return -1;
    }
    if (run->mode != GAME_MODES_CLASSIC && run->mode != GAME_MODES_CHALLENGE) return -1;

    pr_rng rng = pr_run_seed_offset_rng(run, CLASSIC_FIXED_BOSS_WAVES_ELITE_FOUR_1 << 8, NULL);
    const pr_trainer_choice ch = e4_fixed[row][seed_item(&rng, 10)];
    if (!ch.b) return ch.a;
    return seed_item(&rng, 2) ? ch.b : ch.a;
}
