/*
 * Dumps what a new trainer battle reads, for run-core, as C: for every TrainerType, its config's
 * flags (doubleOnly, hasDouble, hasGenders, trainerTypeDouble), its party templates (size,
 * getStrength(i), base strength, deduplicated), its partyTemplateFunc as wave segments per mode, and how many names its class has in the
 * English locale (upstream picks a name with randSeedItem, so the count moves the RNG). Run with
 * tools/redump.sh <upstream dir>; writes gen/out/run_trainers.c. Generated: don't edit.
 */
import { getGameMode } from "#app/game-mode";
import { trainerConfigs } from "#trainers/trainer-config";
import { TrainerType } from "#enums/trainer-type";
import { GameManager } from "#test/framework/game-manager";
import { toCamelCase } from "#utils/strings";
import i18next from "i18next";
import * as fs from "node:fs";
import Phaser from "phaser";
import { it } from "vitest";

it("dump trainers", async () => {
  const game = new GameManager(new Phaser.Game({ type: Phaser.HEADLESS }));
  (globalThis as any).__prScene = game.scene;
  await i18next.changeLanguage("en");
  if ((trainerConfigs as any)[0] && Object.values(trainerConfigs).some((c: any) => c.partyTemplates.length > 16)) {
    throw new Error("a trainer has more than 16 party templates: raise the list in run.h");
  }
  const out = process.env.DUMP_OUT ?? "/tmp/run_trainers.c";
  const types = (Object.values(TrainerType).filter(v => typeof v === "number") as number[]).sort((a, b) => a - b);
  const count = (key: string) =>
    i18next.exists(key, { returnObjects: true } as any)
      ? Object.keys(i18next.t(key, { returnObjects: true }) as any).length
      : -1;
  const templates: string[] = [];
  const rows: string[] = [];
  // partyTemplateFunc: a step function of the game mode and currentBattle.waveIndex (no RNG). It is
  // captured by calling it for every mode at waves 1-1000 (checked flat beyond) and with no current
  // battle, and stored as segments: from wave w on, template t.
  const scene: any = (globalThis as any).__prScene;
  const templateKey = new Map<string, number>();
  const segs: string[] = [];
  const tpl = (t: any) => {
    const strengths = Array.from({ length: Math.min(t.size, 8) }, (_, i) => t.getStrength(i));
    const key = `{${t.size}, ${t.strength ?? -1}, {${strengths.join(", ") || "0"}}}`;
    if (!templateKey.has(key)) {
      templateKey.set(key, templates.length);
      templates.push(key);
    }
    return templateKey.get(key)!;
  };
  const probe = (config: any) => {
    const start = segs.length;
    const saved = scene.currentBattle;
    const savedMode = scene.gameMode;
    for (const mode of [0, 1, 2, 3, 4]) {
      scene.gameMode = getGameMode(mode);
      scene.currentBattle = null;
      segs.push(`{${mode}, 0, ${tpl(config.partyTemplateFunc())}}`);
      let last = -1;
      scene.currentBattle = { waveIndex: 1 };
      for (let w = 1; w <= 1000; w++) {
        scene.currentBattle.waveIndex = w;
        const t = tpl(config.partyTemplateFunc());
        if (t !== last) {
          segs.push(`{${mode}, ${w}, ${t}}`);
          last = t;
        }
      }
      for (const w of [1500, 3000, 10000]) {
        scene.currentBattle.waveIndex = w;
        if (tpl(config.partyTemplateFunc()) !== last) throw new Error("partyTemplateFunc changes past wave 1000");
      }
    }
    scene.currentBattle = saved;
    scene.gameMode = savedMode;
    return [start, segs.length - start];
  };
  for (const type of types) {
    const config: any = Object.hasOwn(trainerConfigs, type) ? trainerConfigs[type] : trainerConfigs[TrainerType.ACE_TRAINER];
    const list = (config.partyTemplates as any[]).map(tpl);
    const [segStart, segN] = config.partyTemplateFunc ? probe(config) : [0, 0];
    const classKey = `trainersCommon:${toCamelCase(TrainerType[type])}`;
    rows.push(
      `    {${type}, ${config.doubleOnly ? 1 : 0}, ${config.hasDouble ? 1 : 0}, ${config.hasGenders ? 1 : 0}, `
        + `${config.trainerTypeDouble ? 1 : 0}, ${config.partyTemplateFunc ? 1 : 0}, ${list.length}, {${list.join(", ")}}, `
        + `${segStart}, ${segN}, ${count(classKey)}, ${count(`${classKey}.male`)}, ${count(`${classKey}.female`)}},`,
    );
  }
  fs.writeFileSync(
    out,
    [
      "/* Generated by gen/dump-trainers.test.ts from upstream's trainerConfigs and English locale. Do not edit. */",
      '#include "pr/run.h"',
      "",
      `const int pr_trainer_count = ${types.length};`,
      `const pr_trainer_info pr_trainers[${types.length}] = {`,
      ...rows,
      "};",
      `const pr_party_template pr_party_templates[${Math.max(templates.length, 1)}] = {${templates.join(", ")}};`,
      `const pr_template_segment pr_template_segments[${Math.max(segs.length, 1)}] = {${segs.join(", ") || "{0}"}};`,
      "",
    ].join("\n"),
  );
  console.log("trainer types", types.length, "templates", templates.length);
});
