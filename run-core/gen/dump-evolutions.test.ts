/*
 * Dumps what determineEnemySpecies reads, for run-core, as C: for every species (by SpeciesId),
 * speciesDataRegistry.hasPrevolution, getEvolutions (target, level, evoLevelThreshold) in order, and
 * getPrevolutionLevels(true) of the registry's species object (the list upstream derives from the
 * evolution table, in its order). Run with tools/redump.sh <upstream dir>; writes
 * gen/out/run_evolutions.c. The output is generated: don't edit it.
 */
import { speciesDataRegistry } from "#app/globals/global-species-data-registry";
import { GameManager } from "#test/framework/game-manager";
import * as fs from "node:fs";
import Phaser from "phaser";
import { it } from "vitest";

it("dump evolutions", () => {
  new GameManager(new Phaser.Game({ type: Phaser.HEADLESS }));
  const out = process.env.DUMP_OUT ?? "/tmp/run_evolutions.c";
  const ids = Object.keys(speciesDataRegistry.data).map(Number).sort((a, b) => a - b);
  const thr = (t: number[] | undefined) => (t ? `{${t.join(", ")}}` : "{-1, -1, -1}");
  const evos: string[] = [];
  const prevos: string[] = [];
  const rows: string[] = [];
  for (const id of ids) {
    const sp = speciesDataRegistry.getSpecies(id);
    const es = speciesDataRegistry.hasEvolutions(id) ? speciesDataRegistry.getEvolutions(id) : [];
    const evoStart = evos.length;
    for (const e of es) {
      evos.push(`{${e.speciesId}, ${e.level}, ${thr(e.evoLevelThreshold)}}`);
    }
    const ps = sp.getPrevolutionLevels(true) as any[];
    const prevoStart = prevos.length;
    for (const p of ps) {
      prevos.push(`{${p[0]}, ${p[1]}, ${thr(p[2])}}`);
    }
    rows.push(
      `    {${id}, ${speciesDataRegistry.hasPrevolution(id) ? "true" : "false"}, ${evoStart}, ${es.length}, ${prevoStart}, ${ps.length}},`,
    );
  }
  const c = [
    "/* Generated by gen/dump-evolutions.test.ts from upstream's species registry. Do not edit. */",
    '#include "pr/run.h"',
    "",
    `const int pr_species_evo_count = ${ids.length};`,
    `const pr_species_evo pr_species_evos[${ids.length}] = {`,
    ...rows,
    "};",
    `const pr_evo pr_evo_data[${Math.max(evos.length, 1)}] = {${evos.join(", ") || "{0}"}};`,
    `const pr_evo pr_prevo_data[${Math.max(prevos.length, 1)}] = {${prevos.join(", ") || "{0}"}};`,
    "",
  ];
  fs.writeFileSync(out, c.join("\n"));
  console.log("species", ids.length, "evolutions", evos.length, "prevolution entries", prevos.length);
});
