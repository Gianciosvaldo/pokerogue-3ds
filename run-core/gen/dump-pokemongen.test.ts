/*
 * Dumps what the Pokemon constructor reads when it makes a new enemy, for run-core, as C: for every
 * species (by SpeciesId) its malePercent (generateGender), whether ability1 and ability2 are the same
 * and whether it has a hidden ability (generateAbilityIndex), forms.length (getSpeciesFormIndex), and
 * for each form (or the species itself when it has no forms) the types the tera type is picked from
 * (getTypes({includeTeraType: false, bypassSummonData: true, ignoreThirdType: true}) of a non-fused
 * Pokemon: [type1, type2 ?? UNKNOWN] as a Set, UNKNOWN dropped when there are two) and whether
 * generateShinyVariant finds variant data for it. Also every trainer type's specialtyType.
 *
 * The variant data is the assets repo's images/pokemon/variant/_masterlist.json at the commit upstream
 * pins; tools/redump.sh fetches it and passes it as VARIANT_MASTERLIST. (The experimental masterlist
 * adds no keys at that commit, so the expSpritesEnabled setting can't change the answer.)
 * Run with tools/redump.sh <upstream dir>; writes gen/out/run_pokemongen.c. The output is generated:
 * don't edit it.
 */
import { speciesDataRegistry } from "#app/globals/global-species-data-registry";
import { Gender } from "#data/gender";
import { AbilityId } from "#enums/ability-id";
import { PokemonType } from "#enums/pokemon-type";
import { TrainerType } from "#enums/trainer-type";
import { GameManager } from "#test/framework/game-manager";
import { trainerConfigs } from "#trainers/trainer-config";
import * as fs from "node:fs";
import Phaser from "phaser";
import { expect, it } from "vitest";

it("dump pokemon generation data", () => {
  new GameManager(new Phaser.Game({ type: Phaser.HEADLESS }));
  const out = process.env.DUMP_OUT ?? "/tmp/run_pokemongen.c";
  const variantData = JSON.parse(fs.readFileSync(process.env.VARIANT_MASTERLIST as string, "utf8"));
  // run.h's hand-written values; fail loudly if upstream renumbers them
  expect([Gender.GENDERLESS, Gender.MALE, Gender.FEMALE]).toEqual([-1, 0, 1]);
  expect(PokemonType.UNKNOWN).toBe(-1);
  expect(AbilityId.NONE).toBe(0);

  const ids = Object.keys(speciesDataRegistry.data).map(Number).sort((a, b) => a - b);
  const rows: string[] = [];
  const forms: string[] = [];
  let variants = 0;
  for (const id of ids) {
    const sp: any = speciesDataRegistry.getSpecies(id);
    const list = sp.forms.length > 0 ? sp.forms : [sp];
    const start = forms.length;
    for (const f of list) {
      const set = new Set<number>([f.type1, f.type2 ?? PokemonType.UNKNOWN]);
      if (set.size > 1) {
        set.delete(PokemonType.UNKNOWN);
      }
      const types = Array.from(set);
      const key = sp.forms.length > 0 && f.formKey ? `${id}-${f.formKey}` : `${id}`;
      const variant = Object.hasOwn(variantData, key) || Object.hasOwn(variantData, `${id}`);
      variants += variant ? 1 : 0;
      forms.push(`{${types.length}, {${types[0]}, ${types[1] ?? types[0]}}, ${variant ? 1 : 0}}`);
    }
    const male = sp.malePercent == null ? -1 : sp.malePercent;
    rows.push(
      `    {${id}, ${male}, ${sp.ability2 === sp.ability1 ? 1 : 0}, ${sp.abilityHidden ? 1 : 0}, ${sp.forms.length}, ${start}},`,
    );
  }
  const types = Object.values(TrainerType).filter(v => typeof v === "number") as number[];
  const maxType = Math.max(...types);
  const specialty = new Array(maxType + 1).fill(-1);
  for (const t of types) {
    const cfg: any = trainerConfigs[t];
    if (cfg?.hasSpecialtyType()) {
      specialty[t] = cfg.specialtyType;
    }
  }
  const c = [
    "/* Generated by gen/dump-pokemongen.test.ts from upstream's species registry, trainer configs and",
    " * the pinned assets' variant masterlist. Do not edit. */",
    '#include "pr/run.h"',
    "",
    `const int pr_species_gen_count = ${ids.length};`,
    `const pr_species_gen pr_species_gens[${ids.length}] = {`,
    ...rows,
    "};",
    `const pr_form_gen pr_form_gens[${forms.length}] = {`,
    ...forms.map(f => `    ${f},`),
    "};",
    `const int pr_trainer_specialty_count = ${maxType + 1};`,
    `const int8_t pr_trainer_specialty[${maxType + 1}] = {${specialty.join(", ")}};`,
    "",
  ];
  fs.writeFileSync(out, c.join("\n"));
  console.log("species", ids.length, "forms", forms.length, "with variants", variants);
});
