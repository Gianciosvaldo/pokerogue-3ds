/*
 * Dumps upstream's experience table for run-core as C: getLevelTotalExp(level, growthRate) for levels
 * 1 to 99 and every GrowthRate (below level 100 upstream reads its own table, expLevels, which isn't
 * exported). Run with tools/redump.sh <upstream dir>; writes gen/out/run_exp.c. Generated: don't edit.
 */
import { GrowthRate, getLevelTotalExp } from "#data/exp";
import * as fs from "node:fs";
import { it } from "vitest";

it("dump exp", () => {
  const out = process.env.DUMP_OUT ?? "/tmp/run_exp.c";
  const rates = Object.values(GrowthRate).filter(v => typeof v === "number") as number[];
  const rows = rates.map(r => `    {${Array.from({ length: 99 }, (_, i) => getLevelTotalExp(i + 1, r)).join(", ")}},`);
  fs.writeFileSync(
    out,
    [
      "/* Generated by gen/dump-exp.test.ts from upstream's getLevelTotalExp. Do not edit. */",
      '#include "pr/run.h"',
      "",
      `const int32_t pr_exp_table[PR_GROWTH_RATE_COUNT][99] = {`,
      ...rows,
      "};",
      "",
    ].join("\n"),
  );
  // run.h declares GrowthRate by hand (it isn't in src/enums): check it still matches
  const expected = ["ERRATIC", "FAST", "MEDIUM_FAST", "MEDIUM_SLOW", "SLOW", "FLUCTUATING"];
  if (rates.length !== expected.length || expected.some((name, i) => (GrowthRate as any)[name] !== i)) {
    throw new Error("GrowthRate changed upstream: update the enum and PR_GROWTH_RATE_COUNT in run.h");
  }
});
