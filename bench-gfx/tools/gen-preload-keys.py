#!/usr/bin/env python3
"""Writes source/preload_keys.h: the images upstream's loading scene preloads at boot
(src/loading-scene.ts), as gfx.pak keys, for the bench's "upstream-style preload" memory test.

    tools/gen-preload-keys.py PATH/pokerogue [PATH/pokerogue-assets]

English text images (${lang} = en, no key suffix). Event banners, egg-gacha images and the
starting biome are left out (loaded by helper functions, not needed on the 3DS). The Pokemon
icon sheets that loadPokemonIcons() adds are listed from the assets checkout when given.
"""
import os
import re
import sys

game = sys.argv[1]
assets = sys.argv[2] if len(sys.argv) > 2 else None
src = open(os.path.join(game, "src", "loading-scene.ts"), encoding="utf-8").read()
call = re.compile(r'\.load(Image|Atlas)\(\s*([`"])([^`"]+)\2\s*,\s*"([^"]*)"\s*(?:,\s*([`"])([^`"]+)\5\s*)?\)')
keys = []
for m in call.finditer(src):
    _, _, key, folder, _, file = m.groups()
    name = file or key
    name = name.replace("${lang}", "en").replace("${keySuffix}", "")
    if "${" in name:
        continue
    if name.endswith(".png"):
        name = name[:-4]
    path = "images/" + (folder + "/" if folder else "") + name
    if path not in keys:
        keys.append(path)
if assets:
    img = os.path.join(assets, "images")
    for f in sorted(os.listdir(img)):
        if re.fullmatch(r"pokemon_icons_\d+v?\.png", f):
            keys.append("images/" + f[:-4])
if assets:
    keys = [k for k in keys if os.path.exists(os.path.join(assets, k + ".png"))]
out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "source", "preload_keys.h")
with open(out, "w") as f:
    f.write("/* Generated by tools/gen-preload-keys.py from upstream src/loading-scene.ts: the images\n"
            " * upstream preloads at boot, as gfx.pak keys. Asset paths only, no art. */\n")
    f.write("static const char* const PRELOAD_KEYS[] = {\n")
    for k in keys:
        f.write(f'    "{k}",\n')
    f.write("};\n#define N_PRELOAD_KEYS ((int)(sizeof PRELOAD_KEYS / sizeof PRELOAD_KEYS[0]))\n")
print(f"{len(keys)} keys -> {out}")
