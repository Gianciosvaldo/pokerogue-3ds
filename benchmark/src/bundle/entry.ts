const g: any = globalThis;
const host = g.__host;
const now = (): number => host.now();
const lines: string[] = [];
function out(s: string) {
  lines.push(s);
  host.print(s);
}
function mb(bytes: number) {
  return (bytes / 1048576).toFixed(1);
}
function memLine(label: string) {
  const m = host.mem();
  out(`  mem ${label}: ${mb(m.cur)} MB in use, peak ${mb(m.peak)} MB`);
}
function stats(xs: number[]) {
  const s = [...xs].sort((a, b) => a - b);
  const q = (p: number) => s[Math.min(s.length - 1, Math.floor(p * (s.length - 1) + 0.5))];
  const mean = s.reduce((a, b) => a + b, 0) / Math.max(1, s.length);
  return { n: s.length, med: q(0.5), p90: q(0.9), max: s[s.length - 1] ?? 0, mean };
}
const fmtMs = (x: number) => (x >= 1000 ? `${(x / 1000).toFixed(2)}s` : `${Math.round(x)}ms`);

// Diverse, realistic late-game party. Level 100 avoids level-up/evolution prompts.
const PARTY = [
  SpeciesId.GARCHOMP,
  SpeciesId.BLAZIKEN,
  SpeciesId.GRENINJA,
  SpeciesId.GARDEVOIR,
  SpeciesId.CORVIKNIGHT,
  SpeciesId.TOXAPEX,
] as const;

/** Target: first living enemy. Move: the usable attack with the best power x type effectiveness against it. */
function pickTarget(game: GameManager) {
  return game.scene.getEnemyField().find(e => e.isActive(true)) ?? game.scene.getEnemyField()[0];
}
function pickMove(game: GameManager, idx: number) {
  const mon = game.scene.getPlayerField()[idx];
  const target = pickTarget(game);
  let best = mon.getMoveset()[0];
  let bestScore = -1;
  for (const pm of mon.getMoveset()) {
    if (!pm || pm.ppUsed >= pm.getMovePp()) {
      continue;
    }
    const move = pm.getMove();
    const eff = target ? target.getAttackTypeEffectiveness(mon.getMoveType(move), { source: mon, move }) : 1;
    const score = Math.max(move.power, 0) * eff;
    if (score > bestScore) {
      best = pm;
      bestScore = score;
    }
  }
  return best.moveId;
}

/** Answer the in-battle menus a player would see, the way a player would, when their phase starts. */
function autoAnswerPrompts(game: GameManager) {
  const pi: any = game.phaseInterceptor;
  const run = pi.run.bind(pi);
  pi.run = (phase: any) => {
    switch (phase.phaseName) {
      case "SelectModifierPhase":
        game.doSelectModifier(); // skip the reward
        break;
      case "SwitchPhase": {
        const party = game.scene.getPlayerParty();
        const slot = party.findIndex((p, i) => i >= game.scene.currentBattle.getBattlerCount() && p.isAllowedInBattle());
        game.doSelectPartyPokemon(Math.max(slot, 0));
        break;
      }
    }
    return run(phase);
  };
}

async function runScenario(name: string, double: boolean, startWave: number, maxTurns: number, phaserGame: Phaser.Game) {
  out(`\n[${name}]`);
  const tSetup = now();
  const realFetch = g.fetch;
  const realRand = BattleScene.prototype.randBattleSeedInt;
  const game = new GameManager(phaserGame);
  // GameManager forces max rolls on every battle RNG call (misses anything under 100% accuracy);
  // restore the real RNG so battles play out normally.
  BattleScene.prototype.randBattleSeedInt = realRand;
  g.fetch = realFetch; // GameManager swaps in an API mock; we serve bundled data files instead
  game.override
    .battleStyle(double ? "double" : "single")
    .startingWave(startWave)
    .startingLevel(100)
    .mysteryEncounterChance(0);
  game.settings.battleStyle(BattleStyle.SET); // no "switch Pokemon?" prompt each wave
  autoAnswerPrompts(game);
  await game.classicMode.startBattle(...PARTY);
  // The test harness gives starters empty movesets (tests always override them). Give each party
  // member a normal level-appropriate moveset, generated by the same code used for enemies.
  for (const mon of game.scene.getPlayerParty()) {
    mon.generateAndPopulateMoveset();
  }
  const setupMs = now() - tSetup;
  out(`  start run + first encounter: ${fmtMs(setupMs)}`);
  memLine("after first encounter");

  const turnTimes: number[] = [];
  if (!double) g.__profStart?.();
  const ticks: number[] = [];
  const waveTimes: number[] = [];
  let waves = 0;
  for (let t = 0; t < maxTurns; t++) {
    const wave = game.scene.currentBattle.waveIndex;
    const phases0 = 0;
    game.phaseInterceptor.clearLogs();
    const t0 = now();
    const ticks0 = g.__ticks;
    const field = game.scene.getPlayerField();
    const target = pickTarget(game).getBattlerIndex();
    const targetFor = (id: MoveId) => (double && !allMoves[id].isMultiTarget() ? target : undefined);
    const m0 = pickMove(game, 0);
    game.move.select(m0, BattlerIndex.PLAYER, targetFor(m0));
    if (double && field.length > 1 && field[1]?.isActive(true)) {
      const m1 = pickMove(game, 1);
      game.move.select(m1, BattlerIndex.PLAYER_2, targetFor(m1));
    }
    try {
      await game.phaseInterceptor.to("TurnInitPhase");
      await game.phaseInterceptor.to("CommandPhase");
    } catch (e) {
      const log = game.phaseInterceptor.phaseLog.slice(phases0).slice(-15).join(",");
      out(`  harness stuck in ${game.scene.phaseManager.getCurrentPhase()?.phaseName}, ui mode ${UiMode[game.scene.ui.mode]}; ending scenario early (not counted). Last phases: ${log}`);
      break;
    }
    const dt = now() - t0;
    ticks.push(g.__ticks - ticks0);
    const newWave = game.scene.currentBattle.waveIndex;
    const phases = game.phaseInterceptor.phaseLog.length - phases0;
    if (newWave !== wave) {
      waves++;
      waveTimes.push(dt);
    } else {
      turnTimes.push(dt);
    }
    if (g.__debug) {
      const e = game.scene.currentBattle.enemyParty.map(p => `${p.name} ${p.hp}/${p.getMaxHp()} L${p.level}`).join(", ");
      out(`    enemy: ${e}; player move ${MoveId[pickMove(game, 0)]}; phases: ${game.phaseInterceptor.phaseLog.slice(phases0).join(",")}`);
    }
    // Harness-only retention, not game state: the mock texture manager keeps every sprite/text it ever
    // created, and the interceptor logs every phase name. Drop both so memory reflects the game.
    const mockList = (game.scene.textures as any).list;
    if (Array.isArray(mockList)) {
      mockList.length = 0;
    }
    game.phaseInterceptor.clearLogs();
    if (t === 4) g.__snapA?.();
    if (t === 19) g.__snapB?.();
    if (g.__debug) {
      const sys: any = game.scene.sys;
      out(`    updateList ${sys.updateList?._active?.length}/${sys.updateList?._pending?.length} displayList ${sys.displayList?.list?.length} field ${game.scene.field?.list?.length}`);
    }
    const m = host.mem();
    out(`  turn ${t + 1} wave ${wave}${newWave !== wave ? `->${newWave}` : ""}: ${fmtMs(dt)} (${phases} phases, ${mb(m.cur)} MB)`);
  }
  const a = stats(turnTimes);
  const b = stats(waveTimes);
  out(`  TURNS (no wave change): n=${a.n} median ${fmtMs(a.med)} p90 ${fmtMs(a.p90)} max ${fmtMs(a.max)}`);
  out(`  TURN+NEXT WAVE: n=${b.n} median ${fmtMs(b.med)} p90 ${fmtMs(b.p90)} max ${fmtMs(b.max)}`);
  if (double) g.__profStop?.();
  memLine("end of scenario");
  const gcMs = host.gc();
  memLine(`after full GC (took ${fmtMs(gcMs)})`);
  clearInterval(PromptHandler.runInterval);
  PromptHandler.runInterval = undefined;
  return { turnTimes, waveTimes, waves, ticks };
}

async function main() {
  const tBody = now();
  out(`PokeRogue headless battle benchmark (${host.platform})`);
  out(`  module load+eval (incl. i18n, species/move tables): ${fmtMs(tBody - g.__t0)}`);
  memLine("after module eval");

  // Same stubs as upstream's test/setup/test-file-initialization.ts
  if (g.__lightMockDestroy) {
    // Experiment: skip destroying the real Phaser sprite hidden inside each mock sprite. Its event
    // listener lists grow with every leaked mock, making each destroy O(n). Pure harness cost.
    MockSprite.prototype.destroy = function (this: any) {
      this.phaserSprite.active = false;
    } as any;
  }
  BBCodeText.prototype.destroy = () => null;
  BBCodeText.prototype.resize = () => null as any;
  Phaser.GameObjects.Image = MockImage as any;
  setCookie(SESSION_ID_COOKIE_NAME, "fake_token");
  g.HTMLCanvasElement.prototype.getContext = () => mockContext;

  const tInit = now();
  await initializeGame();
  const { audioManager } = await import("#app/global-audio-manager");
  audioManager.playBgm = () => null;
  audioManager.replaceBgmUntilEnd = () => null!;
  out(`  initializeGame (all game data): ${fmtMs(now() - tInit)}`);
  memLine("after initializeGame");

  const phaserGame = new Phaser.Game({ type: Phaser.HEADLESS });
  const single = await runScenario("single battles, wave 21+", false, 21, g.__turns ?? 25, phaserGame);
  const dbl = await runScenario("double battles, wave 51+", true, 51, g.__turns ?? 17, phaserGame);

  const all = stats([...single.turnTimes, ...dbl.turnTimes]);
  const allW = stats([...single.waveTimes, ...dbl.waveTimes]);
  // Harness overhead: the test harness polls on a 1 ms virtual timer (mock clock, prompt handler,
  // waitUntil). Time idle ticks, when no game work is pending, to bound that cost per turn.
  const tIdle = now();
  for (let i = 0; i < 500; i++) {
    g.__runTimers();
  }
  const idleTick = (now() - tIdle) / 500;
  const tk = stats([...single.ticks, ...dbl.ticks]);
  const m = host.mem();
  out(`\nSUMMARY`);
  out(`  harness polling: median ${tk.med} ticks/turn x ${idleTick.toFixed(3)} ms idle tick = ~${fmtMs(tk.med * idleTick)} of each turn is test-harness overhead`);
  out(`  turn median ${fmtMs(all.med)}, p90 ${fmtMs(all.p90)}, max ${fmtMs(all.max)} (n=${all.n})`);
  out(`  turn that ends a wave + next encounter: median ${fmtMs(allW.med)}, max ${fmtMs(allW.max)} (n=${allW.n})`);
  out(`  JS heap peak ${mb(m.peak)} MB, now ${mb(m.cur)} MB`);
  out(`  console.error calls: ${g.__errorCount}`);
  out(`  total wall time: ${fmtMs(now() - g.__t0)}`);
  const every = stats([...single.turnTimes, ...single.waveTimes, ...dbl.turnTimes, ...dbl.waveTimes]);
  out(`  all turns: median ${fmtMs(every.med)}, p90 ${fmtMs(every.p90)} (gate target: about 1s per turn)`);
  host.done(lines.join("\n"));
}

main().catch(e => {
  out(`FATAL: ${e?.message ?? e}\n${e?.stack ?? ""}`);
  host.done(lines.join("\n"));
});
