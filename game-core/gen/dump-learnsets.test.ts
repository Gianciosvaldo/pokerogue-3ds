/*
 * Dumps the form-specific level moves for game-core, as C: every species' formLevelMoves, by formKey, in the
 * order upstream keeps them (SpeciesDataRegistry.getLevelMoves appends formLevelMoves[formKey] to the
 * species' levelMoves; battle-core's tables already carry the species' own levelMoves). Run with
 * tools/redump.sh <upstream dir>; writes gen/out/gc_learnsets.c. The output is generated: don't edit it.
 */
import { speciesDataRegistry } from "#app/globals/global-species-data-registry";
import { GameManager } from "#test/framework/game-manager";
import * as fs from "node:fs";
import Phaser from "phaser";
import { it } from "vitest";

it("dump form level moves", () => {
  new GameManager(new Phaser.Game({ type: Phaser.HEADLESS }));
  const out = process.env.DUMP_OUT ?? "/tmp/gc_learnsets.c";
  const ids = Object.keys(speciesDataRegistry.data).map(Number).sort((a, b) => a - b);
  const lists: string[] = [];
  const rows: string[] = [];
  let moves = 0;
  for (const id of ids) {
    const forms: Record<string, [number, number][]> | undefined = (speciesDataRegistry.getSpeciesData(id) as any)
      .formLevelMoves;
    if (!forms) {
      continue;
    }
    for (const key of Object.keys(forms)) {
      const list = forms[key];
      const name = `gc_flm_${rows.length}`;
      lists.push(`static const gc_level_move ${name}[] = {${list.map(([l, m]) => `{${l}, ${m}}`).join(", ") || "{0, 0}"}};`);
      rows.push(`{${id}, ${JSON.stringify(key)}, ${name}, ${list.length}}`);
      moves += list.length;
    }
  }
  const lines = [
    "/* Generated by gen/dump-learnsets.test.ts from upstream's species registry. Do not edit. */",
    '#include "gc/data.h"',
    "",
    ...lists,
    "",
    `const int gc_form_level_moves_count = ${rows.length};`,
    `const gc_form_level_moves gc_form_level_moves_data[${Math.max(rows.length, 1)}] = {`,
    ...rows.map(r => `    ${r},`),
    "};",
    "",
  ];
  fs.writeFileSync(out, lines.join("\n"));
  console.log(`form level moves: ${rows.length} lists, ${moves} moves`);
});
