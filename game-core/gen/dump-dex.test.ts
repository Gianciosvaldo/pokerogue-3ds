/*
 * Dumps species dex info and default save state (initDexData + initStarterData) for game-core.
 * Writes gen/out/gc_dex.c and /tmp/gc_dex_defaults.txt (or DEX_DEFAULTS_OUT).
 * Run with tools/redump.sh <upstream dir>. The output is generated: don't edit it.
 */
import { defaultStarterSpecies } from "#app/constants";
import { speciesEggMoves } from "#balance/egg-moves";
import { Nature } from "#enums/nature";
import { globalScene } from "#app/global-scene";
import { speciesDataRegistry } from "#app/globals/global-species-data-registry";
import { randSeedItem } from "#utils/common";
import { GameManager } from "#test/framework/game-manager";
import * as fs from "node:fs";
import Phaser from "phaser";
import { it } from "vitest";

it("dump dex", () => {
  new GameManager(new Phaser.Game({ type: Phaser.HEADLESS }));
  const outC = process.env.DUMP_OUT ?? "/tmp/gc_dex.c";
  const outDefaults = process.env.DEX_DEFAULTS_OUT ?? "/tmp/gc_dex_defaults.txt";

  const defaultStarterNatures: number[] = [];
  globalScene.executeWithSeedOffset(
    () => {
      const neutralNatures = [Nature.HARDY, Nature.DOCILE, Nature.SERIOUS, Nature.BASHFUL, Nature.QUIRKY];
      for (const _ of defaultStarterSpecies) {
        defaultStarterNatures.push(randSeedItem(neutralNatures));
      }
    },
    0,
    "default",
  );

  const speciesList = speciesDataRegistry.getAllSpecies();
  const speciesIds = speciesList.map(s => s.speciesId).sort((a, b) => a - b);
  const starterIds = speciesDataRegistry.getAllStarters().sort((a, b) => a - b);

  // 1. Build C file contents (gen/out/gc_dex.c)
  const dexInfoRows: string[] = [];
  for (const s of speciesList) {
    const prevo = speciesDataRegistry.getPrevolution(s.speciesId) ?? 0;
    const malePct = s.malePercent === null ? -1 : Math.round(s.malePercent);
    const hasVar = s.hasVariants() ? "true" : "false";
    const hasAb2 = s.ability2 !== undefined && s.ability2 !== null ? "true" : "false";
    dexInfoRows.push(`    {${s.speciesId}, ${prevo}, ${malePct}, ${hasVar}, ${hasAb2}},`);
  }

  const eggMoveRows: string[] = [];
  for (const id of starterIds) {
    const moves = (speciesEggMoves as any)[id] ?? [];
    const m0 = moves[0] ?? 0;
    const m1 = moves[1] ?? 0;
    const m2 = moves[2] ?? 0;
    const m3 = moves[3] ?? 0;
    eggMoveRows.push(`    {${id}, {${m0}, ${m1}, ${m2}, ${m3}}},`);
  }

  const cLines = [
    "/* Generated by gen/dump-dex.test.ts from upstream's species registry and GameData. Do not edit. */",
    '#include "gc/data.h"',
    "",
    `const uint8_t gc_default_starter_natures[${defaultStarterNatures.length}] = {${defaultStarterNatures.join(", ")}};`,
    "",
    `const int gc_species_dex_info_count = ${speciesList.length};`,
    `const gc_species_dex_info gc_species_dex_info_data[${Math.max(speciesList.length, 1)}] = {`,
    ...dexInfoRows,
    "};",
    "",
    `const int gc_starter_egg_moves_count = ${starterIds.length};`,
    `const gc_starter_egg_moves gc_starter_egg_moves_data[${Math.max(starterIds.length, 1)}] = {`,
    ...eggMoveRows,
    "};",
    "",
  ];
  fs.writeFileSync(outC, cLines.join("\n"));

  // 2. Build default GameData dump file for diff test
  const gameData = globalScene.gameData;
  const defaultLines: string[] = [];

  for (const id of speciesIds) {
    const entry = gameData.dexData[id];
    if (!entry) continue;
    const ivs = entry.ivs || [0, 0, 0, 0, 0, 0];
    defaultLines.push(
      `DEX ${id} ${entry.seenAttr} ${entry.caughtAttr} ${entry.natureAttr} ${entry.seenCount} ${entry.caughtCount} ${entry.hatchedCount} ${ivs.join(" ")}`,
    );
  }

  for (const id of starterIds) {
    const entry = gameData.starterData[id];
    if (!entry) continue;
    let moves = [0, 0, 0, 0];
    if (Array.isArray(entry.moveset)) {
      moves = [entry.moveset[0] ?? 0, entry.moveset[1] ?? 0, entry.moveset[2] ?? 0, entry.moveset[3] ?? 0];
    }
    defaultLines.push(
      `STARTER ${id} ${entry.abilityAttr} ${entry.passiveAttr} ${entry.valueReduction} ${entry.candyCount} ${entry.friendship} ${entry.eggMoves} ${moves.join(" ")} ${entry.classicWinCount}`,
    );
  }

  const u = gameData.unlocks || {};
  defaultLines.push(
    `UNLOCKS ${u.ENDLESS_MODE ? 1 : 0} ${u.MINI_BLACK_HOLE ? 1 : 0} ${u.SPLICED_ENDLESS_MODE ? 1 : 0} ${u.EVIOLITE ? 1 : 0}`,
  );

  fs.writeFileSync(outDefaults, defaultLines.join("\n") + "\n");
});
