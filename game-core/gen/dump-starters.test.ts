/*
 * Dumps the starter select screen's species data for game-core, as C: every starter species (by
 * SpeciesId, speciesDataRegistry.isStarter) with its cost (getStarterCost), and defaultStarterSpecies
 * (the ones a new save has unlocked). Run with tools/redump.sh <upstream dir>; writes
 * gen/out/gc_starters.c. The output is generated: don't edit it.
 */
import { defaultStarterSpecies } from "#app/constants";
import { speciesDataRegistry } from "#app/globals/global-species-data-registry";
import { GameManager } from "#test/framework/game-manager";
import * as fs from "node:fs";
import Phaser from "phaser";
import { it } from "vitest";

it("dump starters", () => {
  new GameManager(new Phaser.Game({ type: Phaser.HEADLESS }));
  const out = process.env.DUMP_OUT ?? "/tmp/gc_starters.c";
  const ids = Object.keys(speciesDataRegistry.data).map(Number).sort((a, b) => a - b);
  const rows: string[] = [];
  for (const id of ids) {
    if (speciesDataRegistry.isStarter(id)) rows.push(`{${id}, ${speciesDataRegistry.getStarterCost(id)}}`);
  }
  const lines = [
    "/* Generated by gen/dump-starters.test.ts from upstream's species registry. Do not edit. */",
    '#include "gc/data.h"',
    "",
    `const int gc_starter_cost_count = ${rows.length};`,
    `const gc_starter_cost_entry gc_starter_costs[${rows.length}] = {`,
    ...rows.map(r => `    ${r},`),
    "};",
    `const int gc_default_starter_count = ${defaultStarterSpecies.length};`,
    `const uint16_t gc_default_starters[${defaultStarterSpecies.length}] = {${defaultStarterSpecies.join(", ")}};`,
    "",
  ];
  fs.writeFileSync(out, lines.join("\n"));
});
