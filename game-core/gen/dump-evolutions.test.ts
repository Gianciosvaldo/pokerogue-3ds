/*
 * Dumps what a player Pokemon's getEvolution() reads, for game-core, as C: for every species (by
 * SpeciesId), speciesDataRegistry.getEvolutions in order, each with its target species, level, item
 * (EvolutionItem), preFormKey and evoFormKey (as form indexes of the species and of the target, -1 for
 * null), and its SpeciesEvolutionCondition data (key and values). Also the moves at level 0 (EVOLVE_MOVE)
 * and the relearn moves are in battle-core's level moves already. Run with tools/redump.sh <upstream dir>;
 * writes gen/out/gc_evolutions.c. The output is generated: don't edit it.
 */
import { speciesDataRegistry } from "#app/globals/global-species-data-registry";
import { GameManager } from "#test/framework/game-manager";
import * as fs from "node:fs";
import Phaser from "phaser";
import { it } from "vitest";

it("dump player evolutions", () => {
  new GameManager(new Phaser.Game({ type: Phaser.HEADLESS }));
  const out = process.env.DUMP_OUT ?? "/tmp/gc_evolutions.c";
  const ids = Object.keys(speciesDataRegistry.data).map(Number).sort((a, b) => a - b);
  const formIndex = (speciesId: number, key: string | null | undefined) => {
    if (key == null) {
      return -1;
    }
    const i = speciesDataRegistry.getSpecies(speciesId).forms.findIndex(f => f.formKey === key);
    return i < 0 ? -2 : i;   // -2: a key no form has (upstream then uses form 0 when it evolves)
  };
  const evos: string[] = [];
  const conds: string[] = [];
  const rows: string[] = [];
  const unknownKeys = new Set<string>();
  for (const id of ids) {
    const es = speciesDataRegistry.hasEvolutions(id) ? speciesDataRegistry.getEvolutions(id) : [];
    const start = evos.length;
    for (const e of es) {
      const cStart = conds.length;
      for (const c of (e.condition?.data ?? []) as any[]) {
        // the values a condition compares with, as a list (a number, or an array of them)
        let vals: number[] = [];
        if ("value" in c) vals = [c.value];
        else if ("move" in c) vals = [c.move];
        else if ("time" in c) vals = c.time;
        else if ("biome" in c) vals = c.biome;
        else if ("gender" in c) vals = [c.gender];
        else if ("pkmnType" in c) vals = [c.pkmnType];
        else if ("speciesCaught" in c) vals = [c.speciesCaught];
        else if ("nature" in c) vals = c.nature;
        else if ("weather" in c) vals = c.weather;
        else if ("itemKey" in c) {
          unknownKeys.add(String(c.itemKey));
          vals = [];
        }
        if (vals.length > 16) throw new Error(`condition with ${vals.length} values`);
        const key = "itemKey" in c ? `"${c.itemKey}"` : "NULL";
        conds.push(`{${c.key}, ${vals.length}, {${vals.join(", ") || "0"}}, ${key}}`);
      }
      evos.push(
        `{${e.speciesId}, ${e.level}, ${e.item ?? 0}, ${formIndex(id, e.preFormKey)}, ${formIndex(e.speciesId, e.evoFormKey)}, ${cStart}, ${conds.length - cStart}}`,
      );
    }
    rows.push(`    {${id}, ${start}, ${es.length}},`);
  }
  const c = [
    "/* Generated by gen/dump-evolutions.test.ts from upstream's species registry. Do not edit. */",
    '#include "gc/data.h"',
    "",
    `const int gc_species_evo_count = ${ids.length};`,
    `const gc_species_evo gc_species_evos[${ids.length}] = {`,
    ...rows,
    "};",
    `const gc_evo gc_evo_data[${Math.max(evos.length, 1)}] = {${evos.join(",\n    ") || "{0}"}};`,
    `const gc_evo_cond gc_evo_conds[${Math.max(conds.length, 1)}] = {${conds.join(",\n    ") || "{0}"}};`,
    "",
  ];
  fs.writeFileSync(out, c.join("\n"));
  console.log("species", ids.length, "evolutions", evos.length, "conditions", conds.length, "item keys", [...unknownKeys]);
});
