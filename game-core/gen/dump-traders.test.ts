/*
 * Dumps what the Global Trade System's generateRandomTraderName reads: the generic trainer classes it may pick (the TrainerType
 * keys after UNKNOWN up to, not including, YOUNGSTER), their camelCase locale key, and per class the English locale's name
 * lists (trainersCommon:<class>, .male, .female): how many entries and how many " & "-separated parts each entry has (a digit per entry) (the
 * name is split on " & " and a part picked, which draws only when there is more than one). The strings themselves stay in the
 * locale; game-core hands the key on. Run with tools/redump.sh <upstream dir>; writes gen/out/gc_traders.c. The output is
 * generated: don't edit it.
 */
import { TrainerType } from "#enums/trainer-type";
import { getEnumKeys } from "#utils/enums";
import { toCamelCase } from "#utils/strings";
import * as fs from "node:fs";
import { expect, it } from "vitest";

it("dump traders", () => {
  const en = JSON.parse(fs.readFileSync("locales/en/trainers-common.json", "utf8"));
  const out = process.env.DUMP_OUT ?? "/tmp/gc_traders.c";
  const names = getEnumKeys(TrainerType);
  const eligible = names.slice(1, names.indexOf(TrainerType[TrainerType.YOUNGSTER] as keyof typeof TrainerType));
  const list = (obj: any, what: string): number[] | null => {
    if (obj == null) return null;
    const keys = Object.keys(obj);
    keys.forEach((k, i) => expect(k, `${what} key ${i}`).toBe(String(i + 1)));
    return keys.map(k => {
      expect(typeof obj[k], `${what} entry ${k}`).toBe("string");
      return obj[k].split(" & ").length;
    });
  };
  const rows: string[] = [];
  const arrays: string[] = [];
  let ai = 0;
  eligible.forEach((n: any, i: number) => {
    const key = toCamelCase(n as string);
    const cls = en[key];
    expect(cls, key).toBeDefined();
    const hasGender = cls.male !== undefined;
    const lists = hasGender ? [null, list(cls.male, `${key}.male`), list(cls.female, `${key}.female`)] : [list(cls, key), null, null];
    if (hasGender) expect(lists[2], `${key}.female`).not.toBeNull();
    const refs = lists.map((l, v) => {
      if (!l) return "0, NULL";
      const name = `parts_${ai++}`;
      arrays.push(`static const char ${name}[] = "${l.join("")}";`);
      return `${l.length}, ${name}`;
    });
    rows.push(`    {"${key}", ${hasGender ? "true" : "false"}, {${refs.map(r => `{${r}}`).join(", ")}}},   /* ${i + 1} ${n} */`);
  });
  const text = `/* Generated by gen/dump-traders.test.ts from the pinned upstream's English locale. Do not edit. */
#include "../../src/internal.h"

${arrays.join("\n")}

const gc_trader_class gc_trader_classes[] = {
${rows.join("\n")}
};
const int gc_trader_class_count = ${rows.length};
`;
  fs.writeFileSync(out, text);
  console.log(`traders: ${rows.length} classes, ${arrays.length} lists`);
});
