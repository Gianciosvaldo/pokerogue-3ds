import { BattleScene } from "#app/battle-scene";
import { getGameMode } from "#app/game-mode";
import { speciesDataRegistry as registry } from "#app/globals/global-species-data-registry";
import { activeOverrides } from "#app/overrides";
import { modifierTypes } from "#data/data-lists";
import { generateModifierType } from "#mystery-encounters/encounter-phase-utils";
import { BattleType } from "#enums/battle-type";
import { GameModes } from "#enums/game-modes";
import { MoveId } from "#enums/move-id";
import { SpeciesId } from "#enums/species-id";
import { EnemyPokemon, Pokemon } from "#field/pokemon";
import { PokemonMove } from "#moves/pokemon-move";
import { GameManager } from "#test/framework/game-manager";
import Phaser from "phaser";
import fs from "node:fs";
import { it,expect,vi } from "vitest";
it("native retained unfused boss moveset snapshots",async()=>{
 const native=BattleScene.prototype.randBattleSeedInt;
 const nativeBaseMovegen=Pokemon.prototype.generateAndPopulateMoveset;
 expect(vi.isMockFunction(nativeBaseMovegen)).toBe(false);
 const nativeMovegen=EnemyPokemon.prototype.generateAndPopulateMoveset;
 expect(vi.isMockFunction(nativeMovegen)).toBe(false);
 const game=new GameManager(new Phaser.Game({type:Phaser.HEADLESS}));
 game.override.battleStyle("single").startingWave(5).enemySpecies(SpeciesId.MAGIKARP).enemyMoveset(MoveId.SPLASH);
 await game.classicMode.startBattle(SpeciesId.MEW);BattleScene.prototype.randBattleSeedInt=native;
 expect(Pokemon.prototype.generateAndPopulateMoveset).toBe(nativeBaseMovegen);
 const scene:any=game.scene,battle=scene.currentBattle;
 for(const [key,value]of Object.entries({ENEMY_MOVESET_OVERRIDE:[],ENEMY_LEVEL_OVERRIDE:0,ENEMY_SPECIES_OVERRIDE:null,ENEMY_FUSION_OVERRIDE:false,ENEMY_FUSION_SPECIES_OVERRIDE:null,ENEMY_IVS_OVERRIDE:null,ENEMY_NATURE_OVERRIDE:null,ENEMY_STATUS_OVERRIDE:0,ENEMY_GENDER_OVERRIDE:null,ENEMY_FORM_OVERRIDES:{},ENEMY_SHINY_OVERRIDE:null,ENEMY_VARIANT_OVERRIDE:null}))vi.spyOn(activeOverrides as any,key,"get").mockReturnValue(value);
 scene.modifiers=[];scene.enemyModifiers=[];battle.battleType=BattleType.WILD;battle.trainer=null;
 const rows:any[]=[];
 scene.gameMode=getGameMode(GameModes.CLASSIC);battle.gameMode=scene.gameMode;
 scene.arena.weather=null;scene.arena.terrain=null;scene.arena.biomeId=0;
 const e:any=scene.addEnemyPokemon(registry.getSpecies(SpeciesId.MAGIKARP),5,0,false,true);
 const inputs=JSON.parse(fs.readFileSync(process.env.LEGACY_MOVESET_INPUT!,"utf8"));
 for(const row of inputs){
  const m=row.input;
  e.species=registry.getSpecies(m.species);e.formIndex=m.form;e.level=m.level;e.id=m.id;
  e.nature=m.nature;e.gender=m.gender;e.abilityIndex=m.abilityIndex;e.ivs=m.ivs;
  e.fusionSpecies=null;e.fusionFormIndex=0;e.fusionAbilityIndex=0;e.fusionGender=-1;
  e.bossSegments=m.boss?2:0;e.trainerSlot=0;e.passive=false;e.moveset=[];
  e.customPokemonData.ability=-1;e.customPokemonData.passive=-1;
  e.resetSummonData();e.resetBattleAndWaveData();e.calculateStats();e.hp=e.stats[0];
  expect([e.isBoss(),e.hasPassive(),e.hasTrainer()]).toEqual([!!m.boss,!!m.passive,false]);
  expect(e.getAbility().id).toBe(m.ability);expect(e.stats).toEqual(m.stats);
  Phaser.Math.RND.state(row.before);
  const installed=Phaser.Math.RND.state();
  expect(installed.split(",").slice(1).map(Number)).toEqual(row.before.split(",").slice(1).map(Number));
  const pool=e.getLevelMoves({startingLevel:1,includeEvolutionMoves:true,includePrevolutionMoves:true});
  expect(Phaser.Math.RND.state()).toBe(installed);
  nativeMovegen.call(e);
  rows.push({...row,pool,after:Phaser.Math.RND.state(),moves:e.moveset.map((v:any)=>({move:v.moveId,used:v.ppUsed,up:v.ppUp,max:v.maxPpOverride??-1}))});
 }
 e.destroy();
 expect(rows).toHaveLength(750);
 fs.writeFileSync(process.env.LEGACY_MOVESET_OUT!,JSON.stringify({version:1,scope:"native unfused boss generator from retained rejected snapshots; not full encounter",weather:0,terrain:0,double:false,rows})+"\n");
},240000);
