#!/usr/bin/env python3
"""Turn the upstream JSON dump (gen/upstream/*.json, written by dump-upstream.test.ts)
into C tables for the battle core (gen/out/).

Generated:
  pr_enums.h    every upstream enum as a C enum (string enums get numbers here)
  pr_attrs.h    one C struct per move/ability attribute class, class ids, is-a table
  pr_data.h/.c  type chart, natures, species + forms, moves, abilities, attr instances
  closures.txt  manifest of every upstream closure (id, owner, sha1 of its source)

Nothing here is hand-edited: rerun after dumping a new upstream commit and diff.
"""
import hashlib
import json
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
IN = os.path.join(HERE, "upstream")
OUT = os.path.join(HERE, "out")


def load(name):
    with open(os.path.join(IN, name)) as f:
        return json.load(f)


def snake(name):
    s = re.sub(r"(?<=[a-z0-9])(?=[A-Z])", "_", name)
    return re.sub(r"[^A-Za-z0-9]+", "_", s).upper().strip("_")


def split_words(v):
    """upstream utils/strings.ts splitWords (enum keys are ASCII)"""
    r = v.strip()
    r = re.sub(r"([a-z\d])([A-Z])", "\\1\0\\2", r)
    r = re.sub(r"([A-Z])([A-Z][a-z])", "\\1\0\\2", r)
    r = re.sub(r"[-_ ]+", "\0", r)
    return r.strip("\0").split("\0")


def camel(v):
    """upstream toCamelCase, which turns enum keys into locale keys (MoveId.DOUBLE_EDGE -> doubleEdge)"""
    return "".join(w.lower() if i == 0 else w[:1].upper() + w[1:].lower() for i, w in enumerate(split_words(v)))


def closure_hash(cl):
    """Source text plus any probed captured values (see dump-upstream.test.ts)."""
    key = cl["src"] + ("\n#cap " + json.dumps(cl["cap"]) if "cap" in cl else "")
    key += "\n#vals " + json.dumps(cl["vals"]) if "vals" in cl else ""
    return hashlib.sha1(key.encode()).hexdigest()[:12]


def c_str(s):
    if s is None:
        return "NULL"
    return json.dumps(s, ensure_ascii=False)


enums = load("enums.json")
str_enums = load("string-enums.json")
classes = load("classes.json")
closures = load("closures.json")
moves = load("moves.json")
abilities = load("abilities.json")
species = load("species.json")
typechart = load("typechart.json")
natures = load("natures.json")
move_sets = load("move-sets.json")
battler_tags = load("battler-tags.json")
form_changes = load("form-changes.json")
# Form change trigger classes, numbered for the per-species bitmask (pr_species.form_change_triggers)
fct_names = sorted({n for v in form_changes.values() for n in v})
assert len(fct_names) <= 32, "form change trigger classes no longer fit a uint32 mask"

# ---------------------------------------------------------------- enums
# Local transformation command inputs already consumed by phases.c. Keep their
# existing values reproducible on redump; they are not upstream enum members.
for key, number in {"MEGA": 5, "DYNAMAX": 6, "GIGANTAMAX": 7}.items():
    assert key not in enums["Command"] and number not in enums["Command"].values()
    enums["Command"][key] = number
# String enums get 0-based numbers in declaration order.
str_enum_num = {name: {v: i for i, v in enumerate(vals.values())} for name, vals in str_enums.items()}

out = []
out.append("/* Generated by gen/gen_tables.py from upstream enums. Do not edit. */")
out.append("#ifndef PR_ENUMS_H\n#define PR_ENUMS_H\n")
for name in sorted(enums):
    pre = snake(name)
    out.append(f"enum pr_{pre.lower()} {{")
    for k, v in enums[name].items():
        out.append(f"    {pre}_{snake(k) if not k.isupper() else k} = {v},")
    out.append("};\n")
for name in sorted(str_enums):
    pre = snake(name)
    out.append(f"/* string enum in upstream */\nenum pr_{pre.lower()} {{")
    for i, (k, v) in enumerate(str_enums[name].items()):
        out.append(f"    {pre}_{snake(k) if not k.isupper() else k} = {i}, /* \"{v}\" */")
    out.append(f"    {pre}_COUNT_ = {len(str_enums[name])}")
    out.append("};")
    # The upstream strings in the same order, for tools that read upstream's values
    out.append(f"#define {pre}_VALUES " + ", ".join(c_str(v) for v in str_enums[name].values()) + "\n")
out.append("#endif")
os.makedirs(OUT, exist_ok=True)
with open(os.path.join(OUT, "pr_enums.h"), "w") as f:
    f.write("\n".join(out) + "\n")

# ---------------------------------------------------------------- attr classes
all_attr_owners = [m for m in moves if m] + [a for a in abilities if a]
inst_by_class = {}
for owner in all_attr_owners:
    for a in owner["attrs"] + (owner.get("chargeAttrs") or []):
        inst_by_class.setdefault(a["$class"], []).append(a)

# Every attr class plus every ancestor, so dispatch can ask "is this a StatMultiplierAbAttr?"
# The port also asks for a few classes that no move or ability carries at this commit
# (ability.hasAttr("PreSummonAbAttr") in canApplyAbility), so they get an id regardless.
REFERENCED_CLASSES = ["PreSummonAbAttr"]
attr_classes = set(inst_by_class) | set(REFERENCED_CLASSES)
for c in list(attr_classes):
    attr_classes.update(classes.get(c, []))
attr_classes = sorted(attr_classes)
class_id = {c: i for i, c in enumerate(attr_classes)}


def field_enum(cls, field, values):
    """Which string enum a string field draws from, or None for free text."""
    cands = [n for n, m in str_enum_num.items() if values and all(v in m for v in values)]
    if not cands:
        return None
    if len(cands) > 1:
        pref = "ArenaTagType" if "Arena" in cls else "BattlerTagType"
        if pref in cands:
            return pref
    return cands[0]


def flatten(obj, prefix=""):
    for k, v in obj.items():
        if k == "$class":
            continue
        yield prefix + k, v


# Work out a C type per (class, field) from every instance seen.
class_fields = {}
for cls, insts in inst_by_class.items():
    fields = {}
    for a in insts:
        for k, v in flatten(a):
            fields.setdefault(k, []).append(v)
    spec = {}
    for k, vals in fields.items():
        nn = [v for v in vals if v is not None]
        if not nn:
            spec[k] = ("null", None)
        elif cls == "PostVictoryStatStageChangeAbAttr" and k == "changes" and all(
            (isinstance(v, dict) and set(v) == {"$fn"}) or
            (isinstance(v, list) and all(isinstance(x, dict) and set(x) == {"stat", "stages"} for x in v))
            for v in nn
        ):
            spec[k] = ("statchanges_source", None)
        elif all(isinstance(v, dict) and "$fn" in v for v in nn):
            spec[k] = ("fn", None)
        elif all(isinstance(v, bool) for v in nn):
            spec[k] = ("bool", None)
        elif all(isinstance(v, (int, float)) and not isinstance(v, bool) for v in nn):
            spec[k] = ("double" if any(isinstance(v, float) for v in nn) else "int", None)
        elif all(isinstance(v, str) for v in nn):
            e = field_enum(cls, k, nn)
            spec[k] = ("enum", e) if e else ("str", None)
        elif all(isinstance(v, list) for v in nn):
            items = [x for v in nn for x in v]
            if all(isinstance(x, int) and not isinstance(x, bool) for x in items):
                spec[k] = ("intlist", None)
            elif all(isinstance(x, str) for x in items):
                e = field_enum(cls, k, items)
                spec[k] = ("enumlist", e) if e else ("strlist", None)
            elif all(isinstance(x, dict) and set(x) <= {"stat", "stages"} for x in items):
                spec[k] = ("statchanges", None)
            else:
                spec[k] = ("json", None)
        elif all(isinstance(v, dict) and ("$move" in v or "$ability" in v) for v in nn):
            spec[k] = ("int", None)  # reference by id
        else:
            spec[k] = ("json", None)
        # nullable: null/undefined in some instance, or missing from it (a `declare`d field left unset)
        spec[k] = spec[k] + (len(nn) != len(insts),)
    class_fields[cls] = spec


def cname(field):
    return re.sub(r"\W", "_", field)


h = ["/* Generated by gen/gen_tables.py. Do not edit. */",
     "#ifndef PR_ATTRS_H\n#define PR_ATTRS_H\n#include <stdint.h>\n#include <stdbool.h>\n",
     "/* A closure id into pr_closures (see closures.txt); PR_NO_FN when absent. */",
     "typedef uint16_t pr_fn_id;\n#define PR_NO_FN 0xFFFFu\n",
     "typedef struct { const int32_t *v; uint8_t n; } pr_intlist;",
     "typedef struct { const char *const *v; uint8_t n; } pr_strlist;",
     "typedef struct { int8_t stat, stages; } pr_statchange;",
     "typedef struct { const pr_statchange *v; uint8_t n; } pr_statchanges;\n",
     "typedef struct { pr_statchanges fixed; pr_fn_id fn; } pr_stat_change_source;\n",
     "enum pr_attr_class {"]
for c in attr_classes:
    h.append(f"    PR_AC_{c} = {class_id[c]},")
h.append(f"    PR_AC_COUNT_ = {len(attr_classes)}\n}};\n")
TYPE = {"bool": "bool", "int": "int32_t", "double": "double", "str": "const char *", "enum": "int16_t",
        "fn": "pr_fn_id", "intlist": "pr_intlist", "enumlist": "pr_intlist", "strlist": "pr_strlist",
        "statchanges": "pr_statchanges", "statchanges_source": "pr_stat_change_source", "json": "const char * /* raw JSON */", "null": "uint8_t /* always null */"}
for cls in sorted(class_fields):
    spec = class_fields[cls]
    h.append(f"/* {cls} ({len(inst_by_class[cls])} uses) : {' > '.join(classes.get(cls, []))} */")
    h.append(f"typedef struct pr_attr_{cls} {{")
    nullable = [k for k, s in spec.items() if s[2]]
    if nullable:
        h.append("    uint32_t nulls; /* bit i set = field i below was null/undefined upstream */")
    for k, s in spec.items():
        note = f" /* {s[1]} */" if s[1] else ""
        h.append(f"    {TYPE[s[0]]} {cname(k)};{note}")
    if not spec:
        h.append("    uint8_t unused_;")
    h.append(f"}} pr_attr_{cls};\n")
h.append("/* One attribute of a move or ability: class id, its AbAttr extraCondition closure")
h.append(" * (PR_NO_FN if none), and a pointer to its pr_attr_<Class> params. */")
h.append("typedef struct { uint16_t cls; pr_fn_id cond; const void *p; } pr_attr;\n")
h.append("/* pr_attr_isa[cls] = bitmap over classes: cls is (or derives from) that class. */")
nwords = (len(attr_classes) + 31) // 32
h.append(f"#define PR_AC_WORDS {nwords}")
h.append("extern const uint32_t pr_attr_isa[PR_AC_COUNT_][PR_AC_WORDS];")
h.append("static inline bool pr_attr_is(uint16_t cls, uint16_t base)\n{ return (pr_attr_isa[cls][base >> 5] >> (base & 31)) & 1u; }\n")
h.append("extern const char *const pr_attr_class_name[PR_AC_COUNT_];")
h.append("#endif")
with open(os.path.join(OUT, "pr_attrs.h"), "w") as f:
    f.write("\n".join(h) + "\n")

# ---------------------------------------------------------------- data C file
c = ["/* Generated by gen/gen_tables.py from upstream data. Do not edit. */",
     '#include "pr_data.h"', "#include <stddef.h>\n"]

# is-a bitmaps
c.append("const uint32_t pr_attr_isa[PR_AC_COUNT_][PR_AC_WORDS] = {")
for cls in attr_classes:
    words = [0] * nwords
    for base in [cls] + classes.get(cls, []):
        if base in class_id:
            i = class_id[base]
            words[i >> 5] |= 1 << (i & 31)
    c.append("    {" + ", ".join(f"0x{w:08x}u" for w in words) + "},")
c.append("};\n")
c.append("const char *const pr_attr_class_name[PR_AC_COUNT_] = {")
c += [f'    "{cls}",' for cls in attr_classes]
c.append("};\n")

# type chart and natures
c.append(f"const uint8_t pr_type_chart_x2[{len(typechart)}][{len(typechart)}] = {{ /* multiplier x2, [attack][defend] */")
for row in typechart:
    c.append("    {" + ", ".join(str(int(v * 2)) for v in row) + "},")
c.append("};\n")
c.append(f"const double pr_nature_mult[{len(natures)}][6] = {{")
for row in natures:
    c.append("    {" + ", ".join(repr(float(v)) for v in row) + "},")
c.append("};\n")

# attr instances
blob = []  # extra arrays for lists
counter = [0]
stat_change_sources = []


def emit_list(ctype, items):
    counter[0] += 1
    name = f"L{counter[0]}"
    blob.append(f"static const {ctype} {name}[] = {{{', '.join(items)}}};")
    return name


def value(cls, k, s, v):
    kind, enum = s[0], s[1]
    if v is None:
        return {"str": "NULL", "json": "NULL", "fn": "PR_NO_FN", "intlist": "{0}", "enumlist": "{0}",
                "strlist": "{0}", "statchanges": "{0}", "statchanges_source": "{{0}, PR_NO_FN}"}.get(kind, "0")
    if kind == "bool":
        return "true" if v else "false"
    if kind in ("int", "double"):
        if isinstance(v, dict):
            v = v.get("$move", v.get("$ability"))
        return repr(v) if kind == "double" else str(int(v))
    if kind == "str":
        return c_str(v)
    if kind == "enum":
        return str(str_enum_num[enum][v])
    if kind == "fn":
        return str(v["$fn"])
    if kind == "intlist":
        return "{%s, %d}" % (emit_list("int32_t", [str(x) for x in v]), len(v)) if v else "{0}"
    if kind == "enumlist":
        return "{%s, %d}" % (emit_list("int32_t", [str(str_enum_num[enum][x]) for x in v]), len(v)) if v else "{0}"
    if kind == "strlist":
        return "{%s, %d}" % (emit_list("char *const", [c_str(x) for x in v]), len(v)) if v else "{0}"
    if kind == "statchanges":
        return "{%s, %d}" % (emit_list("pr_statchange", ["{%d, %d}" % (x["stat"], x["stages"]) for x in v]), len(v)) if v else "{0}"
    if kind == "statchanges_source":
        if isinstance(v, dict):
            return "{{0}, %d}" % v["$fn"]
        # An independent name series keeps existing generated lists stable.
        name = f"VSC{len(stat_change_sources)}"
        fixed = "{0}"
        if v:
            stat_change_sources.append(name)
            items = ", ".join("{%d, %d}" % (x["stat"], x["stages"]) for x in v)
            blob.append(f"static const pr_statchange {name}[] = {{{items}}};")
            fixed = "{%s, %d}" % (name, len(v))
        return "{%s, PR_NO_FN}" % fixed
    if kind == "json":
        return c_str(json.dumps(v))
    return "0"


inst_lines = []
attr_rows = []  # flat pr_attr table
effect_rows = []  # pr_attr_effects, parallel to attr_rows


def emit_attrs(attrs):
    start = len(attr_rows)
    for a in attrs:
        cls = a["$class"]
        spec = class_fields[cls]
        name = f"A{len(attr_rows)}"
        inits = []
        nulls = 0
        for i, (k, s) in enumerate(spec.items()):
            v = a.get(k)
            if v is None and s[2]:
                nulls |= 1 << i
            inits.append(f".{cname(k)} = {value(cls, k, s, v)}")
        if any(s[2] for s in spec.values()):
            inits.insert(0, f".nulls = 0x{nulls:x}u")
        inst_lines.append(f"static const pr_attr_{cls} {name} = {{{', '.join(inits) or '0'}}};")
        ec = a.get("extraCondition")
        cond = ec["$fn"] if isinstance(ec, dict) and "$fn" in ec else "PR_NO_FN"
        attr_rows.append(f"{{PR_AC_{cls}, {cond}, &{name}}}")
        effect_rows.append(effect_info(a))
    return start, len(attrs)


def effect_info(a):
    """MoveEffectAttr's option getters (trigger, firstHitOnly...) for one attr; zeros otherwise."""
    if "MoveEffectAttr" not in classes.get(a["$class"], []):
        return "{0}"
    o = a.get("options") if isinstance(a.get("options"), dict) else {}
    cond = o.get("condition")
    eco = o.get("effectChanceOverride")
    return "{%d, %s, %s, %s, %s, %d, %s}" % (
        o.get("trigger", 1), "true" if a.get("selfTarget") else "false",
        "true" if o.get("firstHitOnly") else "false", "true" if o.get("lastHitOnly") else "false",
        "true" if o.get("firstTargetOnly") else "false", -1 if eco is None else int(eco),
        cond["$fn"] if isinstance(cond, dict) and "$fn" in cond else "PR_NO_FN")


def fn_list(fns):
    """A list of closures: bare {"$fn"} (abilities), or MoveCondition objects whose apply() is
    this.func(...) (moves). Anything else stops the build rather than being dropped."""
    ids = []
    for x in fns:
        if isinstance(x, dict) and "$fn" in x:
            ids.append(str(x["$fn"]))
        elif isinstance(x, dict) and isinstance(x.get("func"), dict) and "$fn" in x["func"] \
                and set(x) == {"$class", "func"}:
            ids.append(str(x["func"]["$fn"]))
        else:
            raise SystemExit(f"condition of unknown shape: {x!r}")
    if not ids:
        return "{0}"
    return "{%s, %d}" % (emit_list("pr_fn_id", ids), len(ids))


