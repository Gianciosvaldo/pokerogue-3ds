#!/usr/bin/env python3
"""Writes game/gen/gm_enum_names.{c,h}: every enum in battle-core's generated pr_enums.h with
its upstream member names, so the game can build upstream's locale and asset keys
(SpeciesId.MR_MIME -> "pokemon:mrMime", BiomeId.PLAINS -> "plains_bg"...).

battle-core is read, never changed. Run from the repo root or game/:
    python3 game/tools/gen_enum_names.py
"""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
GAME = os.path.dirname(HERE)
SRC = os.path.join(GAME, "..", "battle-core", "gen", "out", "pr_enums.h")
OUT_C = os.path.join(GAME, "gen", "gm_enum_names.c")
OUT_H = os.path.join(GAME, "gen", "gm_enum_names.h")


def camel_to_prefix(name):
    # pr_species_id -> SPECIES_ID_ (the member prefix battle-core's generator uses)
    return name[len("pr_"):].upper() + "_"


def main():
    text = open(SRC, encoding="utf-8").read()
    enums = []
    for m in re.finditer(r"enum (pr_\w+) \{(.*?)\};", text, re.S):
        ename, body = m.group(1), m.group(2)
        prefix = camel_to_prefix(ename)
        members = []
        for mm in re.finditer(r"^\s*(\w+)\s*=\s*(-?\d+),", body, re.M):
            ident, val = mm.group(1), int(mm.group(2))
            if not ident.startswith(prefix):
                print(f"warning: {ident} lacks prefix {prefix}", file=sys.stderr)
                continue
            members.append((val, ident[len(prefix):]))
        if members:
            enums.append((ename, members))
    h = ["/* Generated by game/tools/gen_enum_names.py from battle-core/gen/out/pr_enums.h. Do not edit. */",
         "#ifndef GM_ENUM_NAMES_H", "#define GM_ENUM_NAMES_H", "",
         "/* Upstream's member names for each battle-core enum (e.g. GM_E_SPECIES_ID, 122 -> \"MR_MIME\"). */",
         "typedef enum {"]
    for ename, _ in enums:
        h.append(f"  GM_E_{ename[3:].upper()},")
    h += ["  GM_E_COUNT_", "} gm_enum;", "",
          "/* NULL when the value isn't a member. */",
          "const char* gm_enum_name(gm_enum e, int value);",
          "/* The member's value by name, or def when absent. */",
          "int gm_enum_value(gm_enum e, const char* name, int def);",
          "/* Upstream's toCamelCase / toLowerCase of a member name into out (\"MR_MIME\" -> \"mrMime\" / \"mr_mime\"). */",
          "const char* gm_enum_camel(gm_enum e, int value, char* out, int n);",
          "const char* gm_enum_lower(gm_enum e, int value, char* out, int n);",
          "", "#endif", ""]
    c = ["/* Generated by game/tools/gen_enum_names.py from battle-core/gen/out/pr_enums.h. Do not edit. */",
         "#include <ctype.h>", "#include <string.h>", "#include \"gm_enum_names.h\"", "",
         "typedef struct { int value; const char* name; } gm_member;", ""]
    for ename, members in enums:
        members = sorted(members)
        c.append(f"static const gm_member M_{ename}[] = {{")
        c += [f"  {{{v}, \"{n}\"}}," for v, n in members]
        c.append("};")
    c.append("")
    c.append("static const struct { const gm_member* m; int n; } TABLES[GM_E_COUNT_] = {")
    for ename, members in enums:
        c.append(f"  {{M_{ename}, {len(members)}}},")
    c.append("};")
    c.append(r'''
const char* gm_enum_name(gm_enum e, int value) {
  if ((unsigned)e >= GM_E_COUNT_) return NULL;
  const gm_member* m = TABLES[e].m;
  int lo = 0, hi = TABLES[e].n - 1;
  while (lo <= hi) {
    int mid = (lo + hi) / 2;
    if (m[mid].value == value) return m[mid].name;
    if (m[mid].value < value) lo = mid + 1; else hi = mid - 1;
  }
  return NULL;
}

int gm_enum_value(gm_enum e, const char* name, int def) {
  if ((unsigned)e >= GM_E_COUNT_ || !name) return def;
  for (int i = 0; i < TABLES[e].n; i++)
    if (!strcmp(TABLES[e].m[i].name, name)) return TABLES[e].m[i].value;
  return def;
}

const char* gm_enum_camel(gm_enum e, int value, char* out, int n) {
  const char* s = gm_enum_name(e, value);
  int o = 0;
  if (n <= 0) return out;
  if (s) {
    int word = 0, first = 1;
    for (; *s && o < n - 1; s++) {
      if (*s == '_') { word = 1; continue; }
      char ch = *s;
      if (word && !first) ch = (char)toupper((unsigned char)ch);
      else ch = (char)tolower((unsigned char)ch);
      out[o++] = ch;
      word = 0;
      first = 0;
    }
  }
  out[o] = 0;
  return out;
}

const char* gm_enum_lower(gm_enum e, int value, char* out, int n) {
  const char* s = gm_enum_name(e, value);
  int o = 0;
  if (n <= 0) return out;
  if (s)
    for (; *s && o < n - 1; s++) out[o++] = (char)tolower((unsigned char)*s);
  out[o] = 0;
  return out;
}''')
    os.makedirs(os.path.dirname(OUT_C), exist_ok=True)
    open(OUT_H, "w").write("\n".join(h))
    open(OUT_C, "w").write("\n".join(c) + "\n")
    print(f"{len(enums)} enums, {sum(len(m) for _, m in enums)} members -> {OUT_C}")


if __name__ == "__main__":
    main()
