/*
 * Dumps what the app needs to choose the music the way upstream does, as C.
 *
 * game/gen/gm_bgm_data.c (compiled into the app): for every TrainerType in trainerConfigs, its battleBgm,
 * mixedBattleBgm and victoryBgm, the encounter music Trainer.getEncounterBgm gives for each TrainerVariant, and
 * whether Trainer.getEncounterMessages has any lines for it (the dialogue is loaded by initTrainerTypeDialogue, which
 * upstream's own initializeGame runs); and the species whose category starts with "Paradox" (the legendary-battle
 * check in Battle.getBgmOverride).
 *
 * game/tests/bgm_expected.c (host test only): what upstream's REAL Battle.getBgmOverride returns for wild battles
 * (every species and form, both music preferences, in the End biome and elsewhere, at wave 100 and at the final wave),
 * for every wave of a Classic run, and for every trainer type, variant and music preference before and after the
 * battle starts. The C chooser (game/source/bgm_choose.c) is compared with every one of them (game/tests/bgmtest.c).
 *
 * The Pokemon and the trainer the battle looks at are fakes (Battle.getBgmOverride reads species, formIndex and
 * getFormKey of globalScene.getEnemyParty(), and config, variant and the Trainer.prototype getters of the trainer);
 * the method itself, the species and trainer data are upstream's.
 *
 * Copy into an upstream checkout (game/tools/redump-bgm.sh does) and run
 *   DUMP_OUT_DATA=/abs/gm_bgm_data.c DUMP_OUT_EXPECTED=/abs/bgm_expected.c npx vitest run <this file>
 * The outputs are generated: don't edit them.
 */
import { globalScene } from "#app/global-scene";
import { settings } from "#app/global-settings-manager";
import { getGameMode } from "#app/game-mode";
import { speciesDataRegistry } from "#app/globals/global-species-data-registry";
import { BattleType } from "#enums/battle-type";
import { BiomeId } from "#enums/biome-id";
import { GameModes } from "#enums/game-modes";
import { MysteryEncounterMode } from "#enums/mystery-encounter-mode";
import { TrainerType } from "#enums/trainer-type";
import { Battle } from "#app/battle";
import { Pokemon } from "#field/pokemon";
import { Trainer } from "#field/trainer";
import { trainerConfigs } from "#trainers/trainer-config";
import { GameManager } from "#test/framework/game-manager";
import * as fs from "node:fs";
import Phaser from "phaser";
import { expect, it } from "vitest";

/** every species, by id (upstream's PokemonSpecies objects, the ones Pokemon.species holds) */
const species = () => [...speciesDataRegistry.getAllSpecies()].sort((a, b) => a.speciesId - b.speciesId);

const cstr = (s: string | null | undefined) => (s ? `"${s.replace(/\\/g, "\\\\").replace(/"/g, '\\"')}"` : "NULL");

it("dump bgm", async () => {
  new GameManager(new Phaser.Game({ type: Phaser.HEADLESS }));
  const scene: any = globalScene;
  const classic = getGameMode(GameModes.CLASSIC);
  scene.gameMode = classic;
  const mkBattle = (wave: number, type: BattleType) => {
    const b = new Battle(classic, { waveIndex: wave, battleType: BattleType.WILD, double: false } as any);
    b.battleType = type;
    return b;
  };
  const setArena = (biomeId: number) => {
    scene.arena = { biomeId };
  };
  const setPref = (allGens: boolean) => {
    (settings as any).audio.musicPreference = allGens ? 1 : 0;
    expect(settings.musicPreferenceAllGens).toBe(allGens);
  };
  const fakeMon = (species: any, formIndex: number) => {
    const m: any = { species, formIndex };
    m.getFormKey = () => (Pokemon.prototype.getFormKey as () => string).call(m);
    return m;
  };

  /* ------------------------------------------------------------ gm_bgm_data.c */
  const types = Object.keys(trainerConfigs).map(Number).sort((a, b) => a - b);
  const rows: string[] = [];
  for (const t of types) {
    const c = trainerConfigs[t];
    const enc: (string | undefined)[] = [];
    const msgs: boolean[] = [];
    for (const variant of [0, 1, 2]) {
      const fake: any = { config: c, variant };
      enc.push((Trainer.prototype.getEncounterBgm as () => string).call(fake));
      msgs.push((Trainer.prototype.getEncounterMessages as () => string[]).call(fake)?.length > 0);
    }
    rows.push(
      `    {${t}, ${cstr(c.battleBgm)}, ${cstr(c.mixedBattleBgm)}, ${cstr(c.victoryBgm)}, ` +
        `{${enc.map(cstr).join(", ")}}, ${c.encounterBgm ? 1 : 0}, ${msgs.reduce((m, v, i) => m | (v ? 1 << i : 0), 0)}}, /* ${TrainerType[t]} */`,
    );
  }
  const paradox = species().filter(s => s.category.startsWith("Paradox")).map(s => s.speciesId);
  fs.writeFileSync(
    process.env.DUMP_OUT_DATA ?? "/tmp/gm_bgm_data.c",
    `/* Generated by game/tools/dump-bgm.test.ts from upstream's trainerConfigs, Trainer.getEncounterBgm and species categories. Do not edit. */
#include "bgm_choose.h"

const gm_trainer_bgm gm_trainer_bgms[] = {
${rows.join("\n")}
};
const int gm_trainer_bgm_count = ${types.length};

/* species whose category starts with "Paradox" */
const uint16_t gm_paradox_species[] = {${paradox.join(", ")}};
const int gm_paradox_species_count = ${paradox.length};
`,
  );
  /* the dialogue must be loaded (initTrainerTypeDialogue) or every has-messages bit is 0 */
  const withMsgs = types.filter(t => (Trainer.prototype.getEncounterMessages as () => string[]).call({ config: trainerConfigs[t], variant: 0 })?.length > 0);
  expect(withMsgs.length).toBeGreaterThan(10);

  /* ------------------------------------------------------------ bgm_expected.c */
  const out: string[] = ['/* Generated by game/tools/dump-bgm.test.ts from upstream\'s Battle.getBgmOverride. Do not edit. */', '#include "bgm_expected.h"', ""];

  /* every wave of a Classic run, a wild Magikarp, away from the End */
  setArena(BiomeId.PLAINS);
  setPref(true);
  scene.getEnemyParty = () => [fakeMon(species().find(s => s.speciesId === 129), 0)];
  const waves: string[] = [];
  for (let w = 0; w <= 200; w++) waves.push(cstr(mkBattle(w, BattleType.WILD).getBgmOverride()));
  out.push(`const char *const bgm_expected_wave[201] = {${waves.join(", ")}};`, "");

  /* wild battles by species and form: only the answers that are not "no override" (NULL) are listed */
  const wild: string[] = [];
  const finals: string[] = [];
  for (const s of species()) {
    const nForms = Math.max(s.forms.length, 1);
    for (let f = 0; f < nForms; f++) {
      scene.getEnemyParty = () => [fakeMon(s, f)];
      for (const allGens of [false, true]) {
        setPref(allGens);
        for (const biome of [BiomeId.PLAINS, BiomeId.END]) {
          setArena(biome);
          const r = mkBattle(100, BattleType.WILD).getBgmOverride();
          if (r) wild.push(`    {${s.speciesId}, ${f}, ${allGens ? 1 : 0}, ${biome === BiomeId.END ? 1 : 0}, ${cstr(r)}},`);
        }
      }
      setPref(true);
      setArena(BiomeId.END);
      const fr = mkBattle(200, BattleType.WILD).getBgmOverride();
      if (fr !== "battle_final_encounter") finals.push(`    {${s.speciesId}, ${f}, 1, 1, ${cstr(fr)}},`);
    }
  }
  out.push(
    "const bgm_wild_case bgm_expected_wild[] = {",
    ...wild,
    "};",
    `const int bgm_expected_wild_count = ${wild.length};`,
    "",
    "/* wave 200 (the final boss): every species and form not listed here gets battle_final_encounter */",
    "const bgm_wild_case bgm_expected_final[] = {",
    ...finals,
    "};",
    `const int bgm_expected_final_count = ${finals.length};`,
    "",
  );

  /* trainer battles: [trainer index in gm_trainer_bgms][variant][all gens][started] */
  scene.getEnemyParty = () => [];
  setArena(BiomeId.PLAINS);
  const tr: string[] = [];
  for (const t of types) {
    const cells: string[] = [];
    for (const variant of [0, 1, 2]) {
      for (const allGens of [false, true]) {
        setPref(allGens);
        for (const started of [false, true]) {
          const b = mkBattle(50, BattleType.TRAINER);
          b.trainer = Object.assign(Object.create(Trainer.prototype), { config: trainerConfigs[t], variant });
          b.started = started;
          cells.push(cstr(b.getBgmOverride()));
        }
      }
    }
    tr.push(`    {${cells.join(", ")}}, /* ${TrainerType[t]} */`);
  }
  out.push("const char *const bgm_expected_trainer[][12] = {", ...tr, "};", "");

  /* a mystery encounter in its default mode: no override (the arena's music plays) */
  const me = mkBattle(30, BattleType.MYSTERY_ENCOUNTER);
  me.mysteryEncounter = { encounterMode: MysteryEncounterMode.DEFAULT } as any;
  out.push(`const char *const bgm_expected_me_default = ${cstr(me.getBgmOverride())};`, "");
  fs.writeFileSync(process.env.DUMP_OUT_EXPECTED ?? "/tmp/bgm_expected.c", out.join("\n"));
});
