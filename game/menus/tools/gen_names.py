#!/usr/bin/env python3
"""Writes game/menus/menus_names.c: upstream i18n keys and atlas frame names
for enums, taken from battle-core's generated pr_enums.h (upstream's enum
member names). Run it after battle-core/gen regenerates pr_enums.h:

    python3 game/menus/tools/gen_names.py
"""
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, "..", "..", ".."))
ENUMS = os.path.join(ROOT, "battle-core", "gen", "out", "pr_enums.h")
OUT = os.path.join(HERE, "..", "menus_names.c")


def enum_members(src, name, prefix):
    m = re.search(r"enum %s \{(.*?)\};" % name, src, re.S)
    out = {}
    for mm in re.finditer(r"%s([A-Z0-9_]+) = (-?\d+)," % prefix, m.group(1)):
        out[int(mm.group(2))] = mm.group(1)
    return out


def camel(s):
    """utils/strings.ts toCamelCase for UPPER_SNAKE enum names."""
    words = [w for w in s.split("_") if w]
    return words[0].lower() + "".join(w[:1].upper() + w[1:].lower() for w in words[1:])


def table(ctype, name, members, conv, count=None):
    n = count if count is not None else max(members) + 1
    lines = [f"const char* const {name}[{n}] = {{"]
    for i in range(n):
        v = members.get(i)
        lines.append(f'    "{conv(v)}",' if v else "    NULL,")
    lines.append("};")
    return "\n".join(lines)


def main():
    src = open(ENUMS, encoding="utf-8").read()
    moves = enum_members(src, "pr_move_id", "MOVE_ID_")
    biomes = enum_members(src, "pr_biome_id", "BIOME_ID_")
    natures = enum_members(src, "pr_nature", "NATURE_")
    types = {k: v for k, v in enum_members(src, "pr_pokemon_type", "POKEMON_TYPE_").items() if k >= 0}
    parts = [
        "/* Generated by tools/gen_names.py from battle-core/gen/out/pr_enums.h. Do not edit. */",
        '#include <stddef.h>',
        "",
        "/* toCamelCase(MoveId[id]): the move's key in locales/<lang>/move.json */",
        table("", "menu_move_keys", moves, camel),
        f"const int menu_move_key_count = {max(moves) + 1};",
        "",
        "/* toCamelCase(BiomeId[id]): the biome's key in biome.json */",
        table("", "menu_biome_keys", biomes, camel),
        f"const int menu_biome_key_count = {max(biomes) + 1};",
        "",
        "/* toCamelCase(Nature[n]): the key in nature.json */",
        table("", "menu_nature_keys", natures, camel),
        "",
        "/* PokemonType[t].toLowerCase(): frame names in the types atlas */",
        table("", "menu_type_frames", types, str.lower),
        "",
    ]
    open(OUT, "w", encoding="utf-8").write("\n".join(parts))
    print(f"wrote {OUT}: {len(moves)} moves, {len(biomes)} biomes, {len(natures)} natures, {len(types)} types")


if __name__ == "__main__":
    main()
